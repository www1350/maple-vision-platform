def test_screen_translation_of_stationary_scene_is_not_actor_movement():
    results, beliefs = _run([_frame(i, camera_shift=(0, -4 * i)) for i in range(12)])
    actor = next(track for track in beliefs[-1].tracks if track.class_id == "player")
    assert actor.velocity_px_per_second == (0.0, -80.0)
    assert results[-1].state == "near_rope"
    _assert_no_climb_or_arrival(results)


