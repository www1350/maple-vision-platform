def test_expired_input_cannot_refresh_climb_from_retained_tracks():
    tracker = TemporalStateEstimator(retain_detection_hypotheses=True)
    movement = MovementHypothesisEstimator()
    for frame in _climb_frames()[:7]:
        result = movement.update(tracker.update(frame, frame.timestamp_ms))
    assert result.state == "climbing_candidate"
    frame = _frame(7, player=(150, 188))
    belief = tracker.update(frame, frame.timestamp_ms + 251)
    assert belief.reason == "stale_observation"
    assert not any(track.observed_this_frame for track in belief.tracks)
    result = movement.update(belief)
    _assert_read_only([result])
    assert result.state == "unknown"


