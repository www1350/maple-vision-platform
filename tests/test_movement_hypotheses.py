@pytest.mark.parametrize("other_confidence", [0.95, 0.2])
def test_multiple_players_including_low_confidence_contender_never_choose_an_actor(
    other_confidence,
):
    frames = [
        _frame(
            i,
            player=(150, 300 - 4 * i),
            extras=(Detection("player", (392, 268, 408, 300), other_confidence),),
        )
        for i in range(10)
    ]
    results, beliefs = _run(frames)
    if other_confidence < 0.5:
        # The tracker can retain the confident actor; movement must still refuse
        # to infer ownership or discard the raw low-confidence contender.
        assert any(
            track.observed_this_frame and track.class_id == "player" for track in beliefs[-1].tracks
        )
    assert all(result.state == "unknown" for result in results)
    assert all(result.to_dict()["actor_track_id"] is None for result in results)


