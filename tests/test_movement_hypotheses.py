@pytest.mark.parametrize("fault", ["single_landmark", "disagreement", "size_change"])
def test_unsupported_camera_estimates_cannot_supply_climb_evidence(fault):
    frames = []
    for i in range(10):
        if fault == "single_landmark":
            platforms = ()
        elif fault == "disagreement":
            platforms = (LANDING, _shift(DISTANT_PLATFORM, 0, i * 4))
        else:
            # Centers do not move, but all three terrain boxes change height.
            platforms = tuple(
                (x1, y1 - i, x2, y2 + i) for x1, y1, x2, y2 in (LANDING, DISTANT_PLATFORM)
            )
        ropes = (
            (("rope", (146, 170 - i, 154, 360 + i)),)
            if fault == "size_change"
            else (("rope", ROPE),)
        )
        frames.append(_frame(i, player=(150, 300 - 4 * i), ropes=ropes, platforms=platforms))
    results, _ = _run(frames)
    _assert_no_climb_or_arrival(results)
    assert results[-1].state == "unknown"


