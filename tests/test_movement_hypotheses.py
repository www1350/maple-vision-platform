def test_deterministic_bounded_history_and_detached_output_preserve_input_beliefs():
    config = MovementConfig(history_size=8)
    frames = [_frame(i) for i in range(100)]
    results, beliefs = _run(frames, config)
    reversed_frames = [
        replace(frame, detections=tuple(reversed(frame.detections))) for frame in frames
    ]
    reordered, _ = _run(reversed_frames, config)
    assert [result.to_dict() for result in results] == [result.to_dict() for result in reordered]
    assert all(len(result.to_dict()["evidence_frames"]) <= 8 for result in results)
    movement = MovementHypothesisEstimator(config)
    original = [belief.to_dict() for belief in beliefs]
    for belief in beliefs:
        final = movement.update(belief)
    assert [belief.to_dict() for belief in beliefs] == original
    expected = final.to_dict()
    changed = final.to_dict()
    changed["evidence_frames"].clear()
    changed["reasons"].append("mutated externally")
    changed["camera"].clear()
    assert final.to_dict() == expected
