"""Independent geometric sequences exercise read-only movement hypotheses.

These authored boxes are engineering fixtures, not labels for a real recording.
Every ordinary scenario first passes through the existing observation tracker;
no expected movement state is generated by the movement implementation.
"""

import json
from dataclasses import FrozenInstanceError, replace

import pytest

from maple_vision.contracts import Detection, Status
from maple_vision.movement_hypotheses import MovementConfig, MovementHypothesisEstimator
from maple_vision.state_estimation import TemporalStateEstimator
from maple_vision.vision import VisualObservation

ROPE = (146.0, 170.0, 154.0, 360.0)
LANDING = (80.0, 180.0, 240.0, 192.0)
DISTANT_PLATFORM = (400.0, 100.0, 580.0, 112.0)
STATES = {"unknown", "near_rope", "climbing_candidate", "platform_arrival_candidate"}


def _shift(box, dx, dy):
    x1, y1, x2, y2 = box
    return x1 + dx, y1 + dy, x2 + dx, y2 + dy


def _frame(
    sequence,
    *,
    player=(150.0, 300.0),
    actor_confidence=0.95,
    ropes=(("rope", ROPE),),
    platforms=(LANDING, DISTANT_PLATFORM),
    extras=(),
    camera_shift=(0.0, 0.0),
    timestamp_ms=None,
    source_id="independent-movement-fixture",
    status=Status.UNKNOWN,
):
    """Player coordinates are center x and feet y, before camera translation."""
    detections = []
    if player is not None:
        x, feet = player
        detections.append(Detection("player", (x - 8, feet - 32, x + 8, feet), actor_confidence))
    detections.extend(Detection(name, box, 0.95) for name, box in ropes)
    detections.extend(Detection("platform", box, 0.95) for box in platforms)
    detections.extend(extras)
    dx, dy = camera_shift
    return VisualObservation(
        sequence=sequence,
        timestamp_ms=sequence * 50 if timestamp_ms is None else timestamp_ms,
        status=status,
        confidence=0.95,
        detections=tuple(replace(item, bbox=_shift(item.bbox, dx, dy)) for item in detections),
        hp_ratio=0.8 if status is Status.KNOWN else None,
        mp_ratio=0.7 if status is Status.KNOWN else None,
        map_id="authored-map" if status is Status.KNOWN else None,
        source_id=source_id,
    )


def _run(frames, config=None):
    tracker = TemporalStateEstimator(retain_detection_hypotheses=True)
    movement = MovementHypothesisEstimator(config)
    beliefs = [tracker.update(frame, frame.timestamp_ms) for frame in frames]
    results = [movement.update(belief) for belief in beliefs]
    _assert_read_only(results)
    return results, beliefs


def _assert_read_only(results):
    for result in results:
        payload = result.to_dict()
        assert payload["state"] in STATES
        assert payload["read_only"] is True
        assert payload["actionable"] is False
        assert payload["action_execution"] == "none"
        assert payload["limitations"]
        assert "controlled_player_id" not in payload
        assert "owner_id" not in payload
        json.dumps(payload, allow_nan=False)


def _climb_frames(*, rope_class="rope"):
    # Authored ascent reaches the platform on source frame 8, then settles.
    feet = (244, 236, 228, 220, 212, 204, 196, 188, 180, 180, 180, 180)
    return [_frame(i, player=(150, y), ropes=((rope_class, ROPE),)) for i, y in enumerate(feet)]


def _assert_no_climb_or_arrival(results):
    assert all(
        result.state not in {"climbing_candidate", "platform_arrival_candidate"}
        for result in results
    )


def test_configuration_is_immutable_and_has_strict_versioned_round_trip():
    config = MovementConfig()
    payload = json.loads(json.dumps(config.to_dict(), allow_nan=False))
    assert payload["schema_version"] == 1
    assert MovementConfig.from_dict(payload) == config
    assert payload["camera_min_landmarks"] >= 2
    assert payload["history_size"] >= payload["min_climb_samples"] >= 3
    with pytest.raises(FrozenInstanceError):
        config.history_size = 128
    payload["history_size"] = 999
    assert config.to_dict()["history_size"] != 999


@pytest.mark.parametrize(
    "change",
    [
        {"schema_version": True},
        {"schema_version": 1.0},
        {"schema_version": 2},
        {"unexpected": 1},
        {"max_gap_ms": True},
        {"max_gap_ms": 0},
        {"history_size": 0},
        {"camera_min_landmarks": 1},
        {"min_actor_confidence": True},
        {"min_terrain_confidence": float("nan")},
        {"min_climb_distance_px": float("inf")},
        {"platform_min_horizontal_overlap_ratio": 1.01},
        {"min_climb_samples": 1},
        {"history_size": 2},
    ],
)
def test_configuration_rejects_ambiguous_or_unsafe_values(change):
    with pytest.raises(ValueError):
        MovementConfig.from_dict(MovementConfig().to_dict() | change)


def test_configuration_requires_complete_object_and_estimator_requires_its_type():
    missing = MovementConfig().to_dict()
    missing.pop("min_arrival_samples")
    for value in (missing, None, [], "configuration"):
        with pytest.raises(ValueError):
            MovementConfig.from_dict(value)
    with pytest.raises(ValueError):
        MovementHypothesisEstimator({})
    with pytest.raises(ValueError):
        MovementHypothesisEstimator().update({})


@pytest.mark.parametrize("rope_class", ["rope", "ladder"])
def test_sustained_ascent_then_stable_support_produces_only_read_only_candidates(rope_class):
    results, beliefs = _run(_climb_frames(rope_class=rope_class))
    assert results[0].state == "unknown"
    assert any(result.state == "climbing_candidate" for result in results[2:8])
    assert all(result.state != "platform_arrival_candidate" for result in results[:9])
    assert results[-1].state == "platform_arrival_candidate"
    assert len({result.to_dict()["actor_track_id"] for result in results[1:]}) == 1
    assert results[-1].to_dict()["platform_track_id"] is not None
    assert all(not belief.actionable for belief in beliefs)
    assert all(belief.observation.map_id is None for belief in beliefs)
    assert all(belief.last_accepted_sequence is None for belief in beliefs)


def test_actionable_upstream_observations_do_not_authorize_movement_output():
    frames = [
        replace(frame, status=Status.KNOWN, hp_ratio=0.8, mp_ratio=0.7, map_id="authored-map")
        for frame in _climb_frames()
    ]
    results, beliefs = _run(frames)
    assert all(belief.actionable for belief in beliefs)
    assert results[-1].state == "platform_arrival_candidate"


def test_stationary_actor_near_rope_never_becomes_climbing():
    results, _ = _run([_frame(i) for i in range(12)])
    assert results[-1].state == "near_rope"
